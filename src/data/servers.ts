export type ServerPreset = { name: string; url: string; note: string };

/** Public test servers with synthetic data and CORS enabled. */
export const PRESETS: ServerPreset[] = [
  { name: "SMART Health IT sandbox", url: "https://r4.smarthealthit.org", note: "Synthetic patients generated by Synthea" },
  { name: "HAPI FHIR public server", url: "https://hapi.fhir.org/baseR4", note: "Community test data, quality varies" },
];

const KEY = "fhir-explorer:server";

export function savedServer(): string {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved) return saved;
  } catch {
    // Storage blocked: use the default.
  }
  return PRESETS[0]!.url;
}

export function saveServer(url: string) {
  try {
    localStorage.setItem(KEY, url);
  } catch {
    // Not persisted; still used for this session.
  }
}

/** Accepts only http(s) URLs, the only kind a browser can query. */
export function validateServerUrl(input: string): string | undefined {
  try {
    const url = new URL(input.trim());
    if (url.protocol !== "https:" && url.protocol !== "http:") return "Use an http or https URL";
    return undefined;
  } catch {
    return "Enter a full URL, such as https://example.org/fhir";
  }
}
